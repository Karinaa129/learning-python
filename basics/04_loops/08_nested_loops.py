# 1. Что такое вложенные циклы?
#    Это цикл, который находится внутри другого цикла.
#    Внешний цикл выполняется один раз, а внутренний
#    пробегает все свои итерации для каждой итерации внешнего.
#
# 2. Пример:
#    for i in range(3):        # внешний цикл
#        for j in range(2):    # внутренний цикл
#            print(i, j)
#
#    Вывод:
#    0 0
#    0 1
#    1 0
#    1 1
#    2 0
#    2 1
#
# 3. Сколько всего итераций?
#    Общее число итераций = (внешние) * (внутренние).
#    В примере выше: 3 * 2 = 6 итераций внутреннего цикла.
#
# 4. Часы как пример вложенных циклов
#    Часовая стрелка делает 12 шагов, минутная — 60 шагов
#    на каждый шаг часовой, секундная — 60 шагов на каждый
#    шаг минутной. Итого: 12 * 60 * 60 = 43 200 секундных шагов.
#
# 5. Операторы break и continue во вложенных циклах
#    - break прерывает только тот цикл, в котором он находится
#      (ближайший).
#    - continue пропускает текущую итерацию только внутреннего
#      (или того, в котором он стоит) цикла.
#
#    Пример с break:
#    for i in range(3):
#        for j in range(5):
#            if j == 2:
#                break
#            print(i, j)
#    Выведет: (0,0),(0,1),(1,0),(1,1),(2,0),(2,1) — внутренний
#    цикл прерывается на j=2 для каждого i.
#
# 6. Частые ошибки:
#     Путать переменные внешнего и внутреннего циклов.
#     Забыть про отступы (внутренний цикл должен быть с отступом).
#     Ожидать, что break выйдет из всех циклов сразу (нет, только
#       из ближайшего).
#     Использовать одинаковые имена переменных для внешнего и
#       внутреннего циклов (будет путаница).
#
# ============================================================

