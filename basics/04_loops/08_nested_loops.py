# Задача 14. Цифровым корнем числа n называется число, получающееся следующим образом: вычисляется сумма цифр числа n, затем сумма цифр у получившегося числа и так далее, пока не получится однозначное число. Например, цифровой корень числа 9875 равен 2:
n = int(input())

while n > 9:                # Внешний цикл: повторяем, пока число не станет однозначным
    current_sum = 0
    temp = n
    
    while temp > 0:         # Внутренний цикл: считаем сумму цифр текущего числа
        current_sum += temp % 10
        temp //= 10
    
    n = current_sum         # Заменяем число на сумму его цифр

print(n)
