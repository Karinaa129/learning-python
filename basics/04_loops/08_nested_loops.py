# Задача 9. Дано натуральное число n. Напишите программу, которая выводит значение суммы: n!
n = int(input())
total = 0

for i in range(1, n + 1):          # Внешний цикл: идём по числам 1, 2, ..., n
    factorial = 1
    
    for j in range(1, i + 1):     # Внутренний цикл: считаем i! как 1*2*...*i
        factorial *= j
    
    total += factorial        # Добавляем текущий факториал к общей сумме

print(total)

