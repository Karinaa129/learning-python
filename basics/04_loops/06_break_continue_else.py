# ============================================================
# Урок 7.6: break, continue, else
# ============================================================
#
# 1. Оператор break
#    Прерывает выполнение ближайшего цикла (for или while).
#    Используется, когда нужно выйти из цикла досрочно.
#
#    Пример:
#    for i in range(10):
#        if i == 5:
#            break
#        print(i)
#    Выведет: 0 1 2 3 4
#
# 2. Оператор continue
#    Пропускает оставшуюся часть тела цикла и переходит
#    к следующей итерации.
#
#    Пример:
#    for i in range(5):
#        if i == 2:
#            continue
#        print(i)
#    Выведет: 0 1 3 4
#
# 3. Бесконечные циклы
#    Часто используют while True вместе с break для выхода.
#
#    Пример:
#    while True:
#        num = int(input())
#        if num == 0:
#            break
#        print(num)
#
# 4. Ключевое слово else в циклах
#    Блок else выполняется, если цикл завершился нормально
#    (без break). Если был break, else не выполняется.
#
#    Пример:
#    for i in range(5):
#        if i == 10:
#            break
#    else:
#        print("Цикл завершился без break")
#
# 5. Частые ошибки:
#     Использовать break вне цикла.
#     Путать break и continue (break — выход, continue — пропуск).
#     Ожидать, что else выполнится после break.
#     Забыть про отступы.
#
# ============================================================

