# Задача 9. На вход программе подаётся натуральное число n. Напишите программу вычисления знакочередующейся суммы:
n = int(input())
total = 0

for i in range(1, n + 1):
    if i % 2 == 1:
        total += i
    else:
        total -= i

print(total)

# Задача 10. На вход программе подаются натуральное число n(n≥2), а затем n различных натуральных чисел последовательности, каждое на отдельной строке. Напишите программу, которая выводит наибольшее и второе наибольшее число последовательности.
n = int(input())

max1, max2 = -1, -1

for _ in range(n):
    num = int(input())
    if num > max1:
        max2 = max1
        max1 = num
    elif num > max2:
        max2 = num
        
print(max1)
print(max2)

