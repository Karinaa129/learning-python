# 1. Что такое цикл while?
#    Цикл while выполняется до тех пор, пока условие истинно.
#    Используется, когда количество повторений заранее неизвестно.
#
# 2. Синтаксис:
#    while условие:
#        тело цикла
#
#    - Условие проверяется перед каждой итерацией.
#    - Если условие сразу ложно, цикл не выполнится ни разу.
#
# 3. Пример:
#    i = 0
#    while i < 5:
#        print(i)
#        i += 1
#    Выведет: 0 1 2 3 4
#
# 4. Считывание данных до стоп-значения
#    Часто используется для ввода данных, пока не встретится
#    определённое значение (например, 0 или "stop").
#    Пример:
#    num = int(input())
#    while num != 0:
#        print(num)
#        num = int(input())
#
# 5. Бесконечный цикл
#    Если условие всегда истинно, цикл будет выполняться бесконечно.
#    Пример: while True:
#                ...
#    Выход из такого цикла обычно делают через break.
#
# 6. Частые ошибки:
#     Забыть изменить переменную внутри цикла (получится бесконечный цикл).
#     Неправильное условие (например, while i > 5 вместо i < 5).
#     Забыть двоеточие.
#     Сделать неправильный отступ.
#
# ============================================================

