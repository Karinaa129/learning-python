# Задача 3. На вход программе подаётся последовательность слов, каждое слово на отдельной строке. Концом последовательности является одно из трёх слов: «стоп», «хватит», «достаточно» (без кавычек). Сами эти слова в последовательность не входят, лишь символизируя её окончание. Напишите программу, которая выводит общее количество членов данной последовательности.
counter = 0
text = input()
while text != 'стоп' and text != 'хватит' and text != 'достаточно':
    text = input()
    counter += 1
print(counter)

# Задача 4. На вход программе подаётся последовательность целых чисел делящихся на 7, каждое число на отдельной строке. Концом последовательности является любое число, не делящееся на 7 (само это число в последовательность не входит, лишь символизируя её конец). Напишите программу, которая выводит члены данной последовательности.
num = int(input())
while num % 7 == 0:
    print(num)
    num = int(input())

# Задача 5. На вход программе подаётся последовательность целых чисел, каждое число на отдельной строке. Признаком окончания последовательности является любое отрицательное число, при этом в саму последовательность оно не входит. Напишите программу, которая выводит сумму всех членов данной последовательности.
total = 0
num = int(input())
while num > -1:
    total += num
    num = int(input())
print(total)    

# Задача 6. На вход программе подаётся последовательность целых чисел от 1 до 5, характеризующее оценку ученика, каждое число на отдельной строке. Концом последовательности является любое неположительное число либо число, большее 5. Напишите программу, которая выводит количество пятерок.
total = 0
num = 1
while 1 <= num <= 5:
    num = int(input())
    if num == 5:
        total += 1
print(total)

