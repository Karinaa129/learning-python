# Задача 6. Дано натуральное число. Напишите программу, которая определяет, состоит ли указанное число из одинаковых цифр.
n = int(input())
min_digit = 9
max_digit = 0

while n > 0:
    last_digit = n % 10

    min_digit = min(min_digit, last_digit)
    max_digit = max(max_digit, last_digit)

    n //= 10

if min_digit == max_digit:
    print("YES")
else:
    print("NO")

# Задача 7. Дано натуральное число. Напишите программу, которая определяет, является ли последовательность его цифр при просмотре справа налево упорядоченной по неубыванию.
n = int(input())
