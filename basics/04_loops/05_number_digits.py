# Задача 1. Дано натуральное число. Напишите программу, которая выводит его цифры в столбик в обратном порядке.
num = int(input())
while num != 0:
    last_digit = num % 10
    print(last_digit)
    num = num // 10

# Задача 2. Дано натуральное число. Напишите программу, которая меняет порядок цифр числа на обратный.
num = int(input())
while num != 0:
    last_digit = num % 10
    num = num // 10
    print(last_digit, end = '')

# Задача 3. Дано натуральное число n(n≥10). Напишите программу, которая определяет его максимальную и минимальную цифры и выводит текст в следующем формате:Максимальная цифра равна <максимальная цифра> Минимальная цифра равна <минимальная цифра>
n = int(input())          # читаем число как целое
max_digit = -1            # изначально меньше любой цифры
min_digit = 10            # изначально больше любой цифры

while n > 0:
    digit = n % 10        # последняя цифра
    if digit > max_digit:
        max_digit = digit
    if digit < min_digit:
        min_digit = digit
    n //= 10              # убираем последнюю цифру

print("Максимальная цифра равна", max_digit)
print("Минимальная цифра равна", min_digit)

# Задача 4. Дано натуральное число. Напишите программу, которая вычисляет:сумму его цифр;количество цифр в нем;произведение его цифр;среднее арифметическое его цифр;его первую цифру;сумму его первой и последней цифры.
n = int(input())

digit_sum = 0
digit_cnt = 0
digit_product = 1
last_digit = n % 10

while n > 0:
    cur_digit = n % 10

    first_digit = cur_digit
    digit_sum += cur_digit
    digit_cnt += 1
    digit_product *= cur_digit
    
    n //= 10

digit_average = digit_sum / digit_cnt
first_last_sum = first_digit + last_digit

print(digit_sum)
print(digit_cnt)
print(digit_product)
print(digit_average)
print(first_digit)
print(first_last_sum)

