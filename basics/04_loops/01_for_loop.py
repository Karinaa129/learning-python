# Задача 6. На вход программе подаётся натуральное число n. Напишите программу, которая для каждого из чисел от 0 до n (включительно) выводит текст в следующем формате:Квадрат числа <текущее число> равен <квадрат текущего числа>
n = int(input())
for i in range(n+1):
    print('Квадрат числа', i, 'равен', i*i)

# Задача 7. На вход программе подаётся натуральное число n(n≥2) – катет прямоугольного равнобедренного треугольника. Напишите программу, которая выводит звёздный треугольник в соответствии с примером.
n = int(input())
for i in range(n):
    print((n-i) *'*')

# Задача 8. На вход программе подаются три натуральных числа m,p,n:m: стартовое количество организмов;p: среднесуточное увеличение в %;n: количество дней для размножения.Напишите программу, которая предсказывает размер популяции организмов с 1-го по n-й день (включительно). Программа должна выводить номер дня, а затем через пробел размер популяции в этот день.
m = int(input())
p = int(input())
n = int(input())
for i in range(n):
    print(i+1, m * (1+(p/100))**i)





