# ============================================================
# Урок 7.1: Цикл for
# ============================================================
#
# 1. Что такое цикл for?
#    Цикл for используется, когда мы заранее знаем, сколько раз
#    нужно повторить действие, или когда нужно перебрать элементы
#    последовательности (строки, списка и т.д.).
#
# 2. Синтаксис:
#    for переменная in последовательность:
#        тело цикла
#
#    - переменная цикла (loop variable) — принимает значение
#      каждого элемента последовательности на каждой итерации.
#    - тело цикла — код с отступом (4 пробела), который
#      выполняется для каждого элемента.
#
# 3. Примеры:
#    for i in "hello":
#        print(i)          # выведет h, e, l, l, o (каждое на новой строке)
#
#    for num in [1, 2, 3]:
#        print(num)        # выведет 1, 2, 3
#
# 4. Переменная цикла:
#    - Имя переменной может быть любым (i, j, num, char и т.д.).
#    - После цикла переменная сохраняет последнее значение.
#    - Если переменная не нужна, можно использовать _ (нижнее подчёркивание).
#
# 5. Частые ошибки:
#     Забыть двоеточие после for.
#     Сделать неправильный отступ.
#     Изменять переменную цикла внутри тела (не рекомендуется).
#     Путать цикл for с условным оператором if.
#
# ============================================================

