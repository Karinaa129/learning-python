# ============================================================
#
# 1. Что такое срез?
#    Срез (slice) позволяет получить часть строки (подстроку).
#    Синтаксис: s[start:stop:step]
#    - start: индекс, с которого начинаем (включается).
#    - stop: индекс, до которого идем (НЕ включается).
#    - step: шаг (по умолчанию 1).
#
# 2. Примеры срезов (s = 'abcdefghij'):
#    s[2:5]   -> 'cde'   (с индекса 2 до 4 включительно)
#    s[:5]    -> 'abcde' (с начала до индекса 4)
#    s[5:]    -> 'fghij' (с индекса 5 до конца)
#    s[:]     -> 'abcdefghij' (вся строка)
#    s[::2]   -> 'acegi' (каждый второй символ)
#    s[1:8:3] -> 'beh'   (от 1 до 7 с шагом 3)
#
# 3. Отрицательные индексы в срезах:
#    s[-3:]   -> 'hij'   (последние 3 символа)
#    s[:-3]   -> 'abcdefg' (всё, кроме последних 3)
#    s[::-1]  -> 'jihgfedcba' (разворот строки задом наперед!)
#
# 4. Изменение символов строки:
#    ⚠️ Строки в Python НЕИЗМЕНЯЕМЫ (immutable).
#    Нельзя просто так взять и заменить символ: s[0] = 'A' (вызовет ошибку).
#    Чтобы изменить символ, нужно создать НОВУЮ строку из кусочков:
#    s = 'X'
#    s = s[:4] + 'X' + s[5:] 
#
# 5. Частые ошибки:
#    ❌ Ожидать, что s[2:5] включит символ с индексом 5.
#    ❌ Пытаться изменить строку по индексу (s[0] = 'x').
#    ❌ Путать s[1:3] и s[3:1] (если start > stop без отрицательного шага, вернется пустая строка).
#
# ============================================================

