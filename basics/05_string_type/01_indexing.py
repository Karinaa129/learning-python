# ============================================================
# Урок 9.1: Строки. Индексация
# ============================================================
#
# 1. Создание строк
#    Строки создаются с помощью парных кавычек: ' ' или " ".
#    Пример:
#    s1 = 'Python'
#    s2 = "Pascal"
#
# 2. Считывание строк
#    Для получения текста от пользователя используется input().
#    Пример:
#    s = input()          # считали текст как строку
#    num = int(input())   # считали текст и преобразовали в число
#
# 3. Пустая строка
#    Создается как s = '' или s = "".
#    Это аналог числа 0 для строк. Длина пустой строки равна 0.
#
# 4. Индексация (доступ к символам)
#    - Каждый символ в строке имеет свой индекс (начиная с 0).
#    - Обращение к символу: s[i].
#    - Отрицательные индексы идут с конца строки (-1 — последний).
#
#    Пример:
#    s = "Python"
#    print(s[0])   # P (первый символ)
#    print(s[1])   # y (второй символ)
#    print(s[-1])  # n (последний символ)
#    print(s[-2])  # o (предпоследний символ)
#
# 5. Итерирование (перебор) строк
#    По строке можно пройтись циклом for:
#    for char in "Python":
#        print(char)  # выведет P, y, t, h, o, n
#
# 6. Частые ошибки:
#    ❌ Выход за пределы длины строки (IndexError).
#       (В строке "Python" индексы от 0 до 5, обращение к s[6] вызовет ошибку).
#    ❌ Складывание строки с числом без str() (TypeError).
#    ❌ Забыть кавычки при создании строки.
#
# ============================================================

