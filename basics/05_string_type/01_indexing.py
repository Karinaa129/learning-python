# Задача 9. На вход программе подаётся одна строка. Напишите программу, которая определяет, сколько раз в строке встречаются символы + и *, и выводит текст в следующем формате:Символ + встречается <n> разСимвол * встречается <m> разгде <n>, <m> – количество вхождений символов + и * в строку соответственно.

s = input()
n = 0
m = 0

for i in range(0, len(s)):
    if s[i] == '+':
        n += 1
    if s[i] == '*':
        m += 1

print('Символ + встречается ' + str(n) + ' раз')
print('Символ * встречается ' + str(m) + ' раз')

