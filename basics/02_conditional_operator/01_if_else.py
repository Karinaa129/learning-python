# ============================================================
# Урок 4.1: Условный оператор if-else
# ============================================================
#
# 1. Условный оператор
#    if условие:
#        # блок кода, если условие истинно
#    else:
#        # блок кода, если условие ложно
#
# 2. Отступы
#    В Python отступы (4 пробела) обязательны.
#    Они показывают, какой код относится к if, а какой — к else.
#
# 3. Операторы сравнения
#    >   больше
#    <   меньше
#    >=  больше или равно
#    <=  меньше или равно
#    ==  равно
#    !=  не равно
#
# 4. Цепочки сравнений
#    Можно писать: if 1 < x < 10:
#    Это значит: x больше 1 И меньше 10 одновременно.
#
# 5. Частые ошибки
#     Забыть двоеточие после условия.
#     Сделать неправильный отступ.
#     Использовать = вместо == в условии.
#     Забыть else, когда он нужен.
#
# ============================================================

