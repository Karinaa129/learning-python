# ============================================================
# Урок 4.2: Логические операторы
# ============================================================
#
# 1. Логическое умножение (and)
#    Условие истинно, только если ОБА выражения истинны.
#    Пример: if x > 0 and x < 10:
#    (x больше 0 И x меньше 10)
#
# 2. Логическое сложение (or)
#    Условие истинно, если ХОТЯ БЫ ОДНО выражение истинно.
#    Пример: if x < 0 or x > 10:
#    (x меньше 0 ИЛИ x больше 10)
#
# 3. Логическое отрицание (not)
#    Меняет значение на противоположное.
#    Пример: if not (x > 0):
#    (если x НЕ больше 0, то есть x <= 0)
#
# 4. Приоритет операторов
#    Сначала выполняется not, потом and, потом or.
#    Но лучше использовать скобки для ясности.
#
# 5. Частые ошибки
#     Путать and и or.
#     Забывать скобки в сложных условиях.
#     Использовать & вместо and, | вместо or.
#     Писать not x > 0 вместо not (x > 0).
#
# ============================================================

