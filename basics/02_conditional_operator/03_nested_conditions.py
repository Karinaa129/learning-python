# ============================================================
# Урок 4.3: Вложенные и каскадные условия
# ============================================================
#
# 1. Вложенные условия
#    Это когда один if находится внутри другого if.
#    Пример:
#        if x > 0:
#            if x % 2 == 0:
#                print("Положительное чётное")
#            else:
#                print("Положительное нечётное")
#        else:
#            print("Не положительное")
#
#    Вложенные условия нужны, когда проверки зависят друг от друга.
#
# 2. Каскадные условия (elif)
#    Это цепочка проверок: if → elif → elif → else.
#    Python проверяет условия по порядку и выполняет ПЕРВОЕ истинное.
#    Пример:
#        if x < 0:
#            print("Отрицательное")
#        elif x == 0:
#            print("Ноль")
#        else:
#            print("Положительное")
#
#    elif — это сокращение от "else if".
#
# 3. Разница между вложенными и каскадными
#    - Вложенные: проверки идут одна внутри другой (зависимые).
#    - Каскадные: проверки идут одна за другой (независимые, но
#      выполняется только первая подходящая).
#
# 4. Когда что использовать
#    - Каскадные (elif) — когда условия взаимоисключающие
#      (например, число либо отрицательное, либо ноль, либо положительное).
#    - Вложенные — когда после первой проверки нужно сделать
#      ещё несколько зависимых.
#
# 5. Частые ошибки
#     Забыть двоеточие после elif.
#     Сделать неправильный отступ (elif должен быть на том же
#       уровне, что и if).
#     Писать else if вместо elif.
#     Путать порядок условий в каскаде — Python выполняет
#       только первое истинное, остальные пропускает.
#
# ============================================================

