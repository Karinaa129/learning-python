# Задача 6. На вход программе подаются два положительных действительных числа a и b​, каждое на отдельной строке. Формат выходных данных Программа должна вывести 4 числа (каждое на отдельной строке) – среднее арифметическое, геометрическое, гармоническое и квадратичное.
