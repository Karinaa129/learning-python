# Задача 7. Даны три действительных числа a, b, c. Напишите программу, которая находит действительные корни квадратного уравнения: Если уравнение имеет один корень, то нужно вывести его, а если уравнение имеет два корня, то следует вывести их в порядке возрастания, каждый на отдельной строке. При этом если уравнение не имеет действительных корней, то программа должна вывести текст «Нет корней» (без кавычек).

from math import *  

a = float(input())
b = float(input())
c = float(input())
d = b**2 - 4*a*c  

if d < 0:
    print('Нет корней')
elif d == 0:
    print(-b / (2*a))
elif d > 0:
    x1 = (-b - d ** 0.5) / (2*a)    # Вычисляет первый корень уравнения
    x2 = (-b + d ** 0.5) / (2*a)    # Вычисляет второй корень уравнения
    print(min(x1, x2))              # Выводит наименьший корень
    print(max(x1, x2))              # Выводит наибольший корень