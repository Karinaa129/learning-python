## Шпаргалка по модулю `math`

### Округления
#| Функция | Описание |
#|---------|----------|
#| `floor(x)` | Округляет число `x` вниз («пол») |
#| `ceil(x)` | Округляет число `x` вверх («потолок») |

### Корни, логарифмы, степени и факториал
#| Функция | Описание |
#|---------|----------|
#| `sqrt(x)` | Квадратный корень числа `x` |
#| `pow(x, n)` | Возведение числа `x` в степень `n` |
#| `log(x)` | Натуральный логарифм числа `x` (основание `e`) |
#| `log10(x)` | Десятичный логарифм числа `x` (основание 10) |
#| `log(x, b)` | Логарифм числа `x` по основанию `b` |
#| `factorial(n)` | Факториал натурального числа `n` |

### Тригонометрия
#| Функция | Описание |
#|---------|----------|
#| `degrees(x)` | Преобразует угол `x` из радиан в градусы |
#| `radians(x)` | Преобразует угол `x` из градусов в радианы |
#| `cos(x)` | Косинус угла `x` (в радианах) |
#| `sin(x)` | Синус угла `x` (в радианах) |
#| `tan(x)` | Тангенс угла `x` (в радианах) |
#| `acos(x)` | Арккосинус `x` (возвращает угол в радианах от 0 до π) |
#| `asin(x)` | Арксинус `x` (возвращает угол в радианах от -π/2 до π/2) |
#| `atan(x)` | Арктангенс `x` (возвращает угол в радианах от -π/2 до π/2) |
#| `atan2(y, x)` | Полярный угол (в радианах) точки с координатами `(x, y)` |

