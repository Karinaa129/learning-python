# 1. Строковый тип данных str
#    - Строка — это последовательность символов в кавычках.
#    - Можно использовать одинарные ' ' или двойные " " кавычки.
#    - Пример: s = "Привет"
#
# 2. Функции len() и str()
#    - len(s) — возвращает длину строки (количество символов).
#    - str(x) — преобразует число или другой объект в строку.
#    - Пример: len("Python") = 6
#
# 3. Конкатенация строк (+)
#    - Оператор + склеивает две строки в одну.
#    - Пример: "Hello" + " " + "World" → "Hello World"
#
# 4. Умножение строки на число (*)
#    - Повторяет строку указанное число раз.
#    - Пример: "ab" * 3 → "ababab"
#
# 5. Оператор in
#    - Проверяет, содержится ли одна строка внутри другой.
#    - Возвращает True или False.
#    - Пример: 'a' in 'map' → True
#
# 6. Частые ошибки
#     Складывать строку с числом без str().
#     Забывать кавычки при создании строки.
#     Путать in (проверка вхождения) с == (полное равенство).
#
# ============================================================

