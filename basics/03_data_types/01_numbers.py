# ============================================================
# Урок 6.1: Числовые типы данных
# ============================================================
#
# 1. Целочисленный тип int
#    - Целые числа: ..., -2, -1, 0, 1, 2, ...
#    - Операции: +, -, *, //, %, **
#    - Пример: x = 10
#
# 2. Числа с плавающей точкой float
#    - Дробные числа: 3.14, -0.5, 2.0
#    - Операции: +, -, *, /, //, %, **
#    - Пример: y = 3.14
#
# 3. Встроенные функции для работы с числами
#    - max(a, b, ...) — возвращает наибольшее значение
#    - min(a, b, ...) — возвращает наименьшее значение
#    - abs(x) — возвращает модуль (абсолютную величину) числа
#
#    Важно: аргументы max() и min() должны поддерживать
#    сравнение между собой (например, нельзя смешивать int и str).
#
# 4. Примеры
#    max(3, 8, -3, 12, 9)   # 12
#    min(3, 8, -3, 12, 9)   # -3
#    abs(-7)                # 7
#    abs(10)                # 10
#    abs(-17.67)            # 17.67
#
# 5. Частые ошибки
#     Передавать в max()/min() несравнимые типы.
#     Забывать, что abs() возвращает неотрицательное число.
#     Путать целочисленное деление // и обычное /.
#
# ============================================================

